# 密度が同じになる理由：質（原子1個の質量）と量（原子1個の体積＝線の長さ）に分ける
# 格子定数は標準的な文献値（要照合）。同位体純粋の質量も併記
import numpy as np
u=1.66053907e-24
def cubic(a,m): return 8*m*u/(a*1e-8)**3, a**3/8
def hexa(a,c,m): V=np.sqrt(3)/2*a**2*c; return 4*m*u/(V*1e-24), V/4
pairs=[("ダイヤモンド","cBN","立方",cubic,(3.5668,),(3.6157,),12.011,(10.81+14.007)/2,12.000,(11.00931+14.00307)/2,(6,),(5,7)),
       ("グラファイト","hBN","層状",hexa,(2.4612,6.7079),(2.5040,6.6612),12.011,(10.81+14.007)/2,12.000,(11.00931+14.00307)/2,(6,),(5,7)),
       ("Si","AlP","立方",cubic,(5.4310,),(5.4635,),28.0855,(26.9815+30.9738)/2,None,None,(14,),(13,15)),
       ("Ge","GaAs","立方",cubic,(5.6579,),(5.6533,),72.630,(69.723+74.9216)/2,None,None,(32,),(31,33))]
print("単体 / 組      形    質量比   体積比   密度比 | 単体の密度  組の密度")
for A,B,f,fn,pa,pb,ma,mb,ma_i,mb_i,za,zb in pairs:
    ra,va=fn(*pa,ma); rb,vb=fn(*pb,mb)
    print(f"{A:6s}/{B:5s} {f:4s}  {mb/ma:.4f}  {vb/va:.4f}  {rb/ra:.4f} | {ra:.3f}  {rb:.3f}")
    if ma_i:
        ra2,_=fn(*pa,ma_i); rb2,_=fn(*pb,mb_i)

"""
TUB-TMCC 28：水素核融合のエネルギー収支 ― 三つの読みを同じ入力で並べる（2026-11-10）

この記録の数値はすべてこのスクリプトで出す。外部ライブラリは使わない。
  python3 28-verify-fusion-energy-balance.py

入力（本人の指定）：水素原子・水素分子・中性子・ヘリウム・電子のエネルギー（質量）
  値は CODATA 2018（粒子）と AME2020（原子質量）。

三つの読み
  読みA「出力そのものがない」：核融合で外へ出るエネルギーは 0
  読みB「源が質量ではない」  ：質（要素数）は保存され、出るのは量（力・拘束）の差
  読みC「比重の誤り」        ：観測質量 = 本当の質量 − 占める空間の数 × 空間1つの質量。
                               見かけの質量欠損は、空間の数が変わったことによる
"""

# ------------------------------------------------------------
# 0. 入力（MeV）
# ------------------------------------------------------------
U = 931.49410242          # 1 u（CODATA 2018）
me = 0.51099895000        # 電子
mp = 938.27208816         # 陽子
mn = 939.56542052         # 中性子
eV = 1e-6                 # MeV

atomic_u = {              # 原子質量（AME2020）
    "H":   1.00782503223,
    "D":   2.01410177812,
    "T":   3.01604928132,
    "He3": 3.01602932197,
    "He4": 4.00260325413,
}
A = {k: v * U for k, v in atomic_u.items()}   # 原子（MeV）

# 電子の結合エネルギー（原子から裸の核へ直すため）
Be = {"H": 13.598434 * eV, "D": 13.6022 * eV, "T": 13.6034 * eV,
      "He3": 79.0 * eV, "He4": 79.005 * eV}
Z = {"H": 1, "D": 1, "T": 1, "He3": 2, "He4": 2}
N = {k: A[k] - Z[k] * me + Be[k] for k in A}  # 裸の核
N["p"] = mp

D0_H2 = 4.4781 * eV                          # 水素分子の解離エネルギー
H2 = 2 * A["H"] - D0_H2                       # 水素分子

line = "=" * 72
print(line)
print("0. 入力（MeV）")
print(f"  電子        {me:.8f}")
print(f"  陽子        {mp:.8f}")
print(f"  中性子      {mn:.8f}")
print(f"  水素原子    {A['H']:.8f}")
print(f"  水素分子    {H2:.8f}   （= 2×水素原子 − 解離 4.478 eV）")
print(f"  ヘリウム原子 {A['He4']:.8f}")
print(f"  ヘリウム核   {N['He4']:.8f}")

# ------------------------------------------------------------
# 1. 反応ごとの Q 値（反応前の質量 − 反応後の質量）
# ------------------------------------------------------------
# 各反応：(名前, 反応前の質量, 反応後の質量, 二体なら(軽い方の名前, 軽い方の質量, 重い方の質量), 測定された出力)
reactions = [
    ("水素原子4つ → ヘリウム原子（太陽の pp 連鎖の正味）",
     4 * A["H"], A["He4"], None,
     "太陽の光度（下の §4 で照合）"),
    ("水素分子2つ → ヘリウム原子",
     2 * H2, A["He4"], None,
     "（分子から出発した場合）"),
    ("D + T → He4 + n",
     A["D"] + A["T"], A["He4"] + mn, ("中性子", mn, N["He4"]),
     "中性子 14.1 MeV（核融合炉・NIF の中性子診断）"),
    ("D + D → He3 + n",
     2 * A["D"], A["He3"] + mn, ("中性子", mn, N["He3"]),
     "中性子 2.45 MeV（D-D 中性子源・核融合診断）"),
    ("D + D → T + p",
     2 * A["D"], A["T"] + A["H"], ("陽子", mp, N["T"]),
     "陽子 3.02 MeV（荷電粒子分光）"),
    ("p + n → D + γ",
     A["H"] + mn, A["D"], ("γ", 0.0, N["D"]),
     "γ線 2.2232 MeV（中性子捕獲γ線の精密測定）"),
    ("n → p + e + ν̄（中性子の崩壊）",
     mn, A["H"], None,
     "電子のエネルギー上限 0.782 MeV"),
    ("e⁻ + e⁺ → γγ",
     2 * me, 0.0, None,
     "γ線 0.511 MeV × 2（PET で毎日使われている）"),
    ("H + H → H₂（化学結合、比較用）",
     2 * A["H"], H2, None,
     "解離エネルギー 4.478 eV"),
]

print(line)
print("1. Q 値（反応前 − 反応後）と、二体に分かれるときの取り分")
Q = {}
for name, before, after, two, measured in reactions:
    q = before - after
    Q[name] = q
    s = f"  {name}\n    Q = {q:.6f} MeV" if q > 1e-3 else f"  {name}\n    Q = {q / eV:.4f} eV"
    if two:
        lname, ml, mh = two
        if ml == 0.0:   # 光子：反跳を引く
            E_light = q - q * q / (2 * mh)
        else:           # 運動量保存（非相対論で十分）
            E_light = q * mh / (ml + mh)
        s += f"\n    運動量保存から {lname} の取り分 = {E_light:.4f} MeV"
    s += f"\n    測定：{measured}"
    print(s)

# ------------------------------------------------------------
# 2. 読みB：質（要素数）の収支
# ------------------------------------------------------------
print(line)
print("2. 読みB：質（要素数）の収支  docs/TTT質量欠損再解釈.md の表")
q_e, q_p, q_n = 500, 1500, 2000
print(f"  電子 {q_e}、陽子 {q_p}、中性子 {q_n}（反電子は −{q_e} とした場合を併記）")

def qual(p, n, e, ebar=0):
    return p * q_p + n * q_n + e * q_e - ebar * q_e

checks = [
    ("水素原子4つ → ヘリウム原子 + 2e⁺(消滅) ", qual(4, 0, 4), qual(2, 2, 2) + 0),
    ("  内訳 p → n + e⁺ + ν（e⁺ を +500）", qual(1, 0, 0), qual(0, 1, 0) + q_e),
    ("  内訳 p → n + e⁺ + ν（e⁺ を −500）", qual(1, 0, 0), qual(0, 1, 0) - q_e),
    ("D + T → He4 + n（核）", qual(1, 1, 0) + qual(1, 2, 0), qual(2, 2, 0) + qual(0, 1, 0)),
    ("D + D → He3 + n（核）", 2 * qual(1, 1, 0), qual(2, 1, 0) + qual(0, 1, 0)),
    ("D + D → T + p（核）", 2 * qual(1, 1, 0), qual(1, 2, 0) + qual(1, 0, 0)),
    ("p + n → D + γ", qual(1, 1, 0), qual(1, 1, 0)),
    ("n → p + e + ν̄", qual(0, 1, 0), qual(1, 0, 1)),
    ("e⁻ + e⁺ → γγ（e⁺ を +500）", 2 * q_e, 0),
    ("e⁻ + e⁺ → γγ（e⁺ を −500）", 0, 0),
]
for name, b, a in checks:
    mark = "保存" if b == a else f"差 {a - b:+d}"
    print(f"  {name:38s} 前 {b:6d}  後 {a:6d}  → {mark}")

# 質 = 2000×(バリオン数) − 500×(電荷) で書けるかを確かめる
print("  質の式の当てはめ：質 = 2000×バリオン数 − 500×電荷")
for nm, B, Qc, val in [("電子", 0, -1, q_e), ("陽電子", 0, +1, -q_e), ("陽子", 1, +1, q_p),
                       ("中性子", 1, 0, q_n), ("光子・ニュートリノ", 0, 0, 0)]:
    calc = 2000 * B - 500 * Qc
    print(f"    {nm:12s} 式 {calc:6d}  表 {val:6d}  {'一致' if calc == val else '不一致'}")

# ------------------------------------------------------------
# 3. 読みC：空間の数で説明できるか
# ------------------------------------------------------------
print(line)
print("3. 読みC：Q = (反応前の空間の数 − 反応後の空間の数) × 空間1つの質量 で説明できるか")
print("  空間の数え方（本人の指定）：水素分子は2空間、ヘリウムは1空間。")
print("  それ以外は、原子・核・自由な粒子を1つにつき1空間とする（仮置き）。光子・ニュートリノは0。")
spaces = [
    ("水素原子4つ → ヘリウム原子（太陽の pp 連鎖の正味）", 4, 1),
    ("水素分子2つ → ヘリウム原子", 4, 1),
    ("D + T → He4 + n", 2, 2),
    ("D + D → He3 + n", 2, 2),
    ("D + D → T + p", 2, 2),
    ("p + n → D + γ", 2, 1),
    ("n → p + e + ν̄（中性子の崩壊）", 1, 1),
]
fits = []
for name, sb, sa in spaces:
    ds = sb - sa
    q = Q[name]
    k = q / ds if ds else float("nan")
    fits.append((name, ds, q, k))
    ks = f"{k:8.4f}" if ds else "  （割れない）"
    print(f"  {name[:34]:34s} Δ空間 {ds:+d}  Q {q:9.4f} MeV  必要な空間1つの質量 {ks}")
print("  同じ D + D から出発して、He3 + n と T + p はどちらも 2空間 → 2空間。")
print(f"  それでも Q は {Q['D + D → He3 + n']:.4f} と {Q['D + D → T + p']:.4f} MeV で違う。")
print("  空間の数だけで決まるなら、この二つは同じ値になるはず。→ 空間の数だけでは説明できない。")

# ------------------------------------------------------------
# 4. 読みA：太陽で照合する
# ------------------------------------------------------------
print(line)
print("4. 読みA（出力 0）と太陽")
S = 1361.0                  # 太陽定数 W/m²（地球の位置で受ける量）
q_pp = Q["水素原子4つ → ヘリウム原子（太陽の pp 連鎖の正味）"]
E_nu = 0.59                 # ニュートリノが持ち去る平均（pp 連鎖、標準太陽模型）
MeV_J = 1.602176634e-13
he_rate = S / ((q_pp - E_nu) * MeV_J)          # 1 m² あたり、1秒にできるヘリウムの数に相当
nu_flux = 2 * he_rate / 1e4                    # 1 cm² あたりのニュートリノ数
print(f"  太陽定数 {S} W/m² を、ヘリウム1個あたり {q_pp - E_nu:.2f} MeV で割る")
print(f"  → 地球に届くニュートリノの予測 {nu_flux:.2e} 個/cm²/s（ヘリウム1個につき2個）")
print("  測定（Borexino 2018, Nature 562, 505）：pp ニュートリノだけで 約 6.1e10 個/cm²/s")
print("  読みA（出力 0）なら、太陽は光らず、この数も出てこない。")

# ------------------------------------------------------------
# 5. 水素分子と水素原子の差は、核融合の出力にどれだけ効くか
# ------------------------------------------------------------
print(line)
print("5. 水素分子（2空間）と水素原子の差")
d = Q["水素原子4つ → ヘリウム原子（太陽の pp 連鎖の正味）"] - Q["水素分子2つ → ヘリウム原子"]
print(f"  Q（原子から） − Q（分子から） = {d / eV:.3f} eV")
print(f"  核融合の出力に対する割合 = {d / q_pp:.2e}")

# ------------------------------------------------------------
# 6. ヘリウムの結合エネルギー（読みBで TTT が出すべき数）
# ------------------------------------------------------------
print(line)
print("6. 読みBで、TTT が力から出すべき数")
B_he = 2 * mp + 2 * mn - N["He4"]
B_d = mp + mn - N["D"]
print(f"  ヘリウム核の結合エネルギー  {B_he:.4f} MeV（陽子2＋中性子2 − ヘリウム核）")
print(f"  重水素の結合エネルギー      {B_d:.4f} MeV")
print(f"  比                          {B_he / B_d:.3f}")
print("  質が保存されるなら、出るエネルギーはすべて量の差で、この数に一致しなければならない。")
print(line)

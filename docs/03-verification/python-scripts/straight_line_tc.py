# 「線のまっすぐさ」と超電導：La3Ni2O7 薄膜（電子線プチコグラフィ, arXiv:2501.08204）
import numpy as np
films=[("SLAO",-1.6,5.33,20.56,1.7,1.2,"する（始まり 約42 K）"),
       ("LAO", -0.9,5.37,20.66,1.4,1.0,"しない（金属）"),
       ("NGO", +0.6,5.45,20.39,4.7,2.0,"しない（金属）"),
       ("STO", +1.8,5.52,20.01,5.9,1.6,"しない（絶縁体）")]
print("基板  ひずみ  a_p(Å)  c/a_p  面内の線の曲がり(°)  八面体    超電導")
for s,e,a,c,dev,err,sc in films:
    ap=a/np.sqrt(2); tilt="一方向" if dev<3 else "交互"
    print(f"{s:4s} {e:+5.1f}%  {ap:.3f}  {c/ap:.3f}   {dev:.1f} ± {err:.1f}          {tilt}   {sc}")
print("\nバルク高圧（約80 K）: a_p = 3.715 Å、Ni–O–Ni 180°（比較）")
